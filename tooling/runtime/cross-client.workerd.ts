import { afterEach, expect, it } from "vitest";
import { SELF, reset } from "cloudflare:test";
import { parseSchema } from "@floodops/contracts";
import { scenarioReference } from "../../apps/api/src/index";
afterEach(reset);
const key = () => crypto.randomUUID();
const request = (path: string, init?: RequestInit) => SELF.fetch("https://floodops.test/api/v1" + path, init);
it("shares a real session across web dispatcher cookie and native driver bearer without a platform role grant", async () => {
  const origin = "https://floodops.test";
  const created = await request("/sessions", { method: "POST", headers: { Origin: origin, "Content-Type": "application/json", "Idempotency-Key": key(), "X-Client-Request-Scope": key(), "CF-Connecting-IP": "192.0.2.25" }, body: JSON.stringify({ scenario_id: scenarioReference.scenario_id, scenario_version: scenarioReference.scenario_version, client_type: "web" }) });
  expect(created.status).toBe(201);
  const owner = parseSchema("SessionCreatedResponse", await created.json()).data;
  const cookieHeader = created.headers.get("Set-Cookie");
  expect(cookieHeader).toContain("HttpOnly; Secure; SameSite=Lax; Path=/");
  expect(owner.credential.access_token).toBeNull();
  const cookie = cookieHeader!.split(";")[0]!;
  const csrf = owner.credential.csrf_token!;
  const sid = owner.session.session_id;
  const body = JSON.stringify({ role: "driver", bound_entity_id: "drv_moto01", expires_in_seconds: 900 });
  const mutation = { Cookie: cookie, Origin: origin, "Content-Type": "application/json", "Idempotency-Key": key() };
  expect((await request("/sessions/" + sid + "/invitations", { method: "POST", headers: mutation, body })).status).toBe(403);
  const invited = await request("/sessions/" + sid + "/invitations", { method: "POST", headers: { ...mutation, "X-CSRF-Token": csrf, "Idempotency-Key": key() }, body });
  expect(invited.status).toBe(201);
  const invite = parseSchema("InviteResponse", await invited.json()).data;
  const claimed = await request("/session-claims", { method: "POST", headers: { "Content-Type": "application/json", "Idempotency-Key": key() }, body: JSON.stringify({ session_id: sid, claim_token: invite.claim_token, client_type: "native" }) });
  expect(claimed.status).toBe(201);
  expect(claimed.headers.get("Set-Cookie")).toBeNull();
  const driver = parseSchema("SessionCreatedResponse", await claimed.json()).data;
  const auth = { Authorization: "Bearer " + driver.credential.access_token };
  expect(driver.session.session_id).toBe(sid);
  expect(driver.participant.bound_entity_id).toBe("drv_moto01");
  expect(driver.participant.role).toBe("driver");
  expect(driver.credential.csrf_token).toBeNull();
  expect((await request("/sessions/" + sid + "/identity", { headers: auth })).status).toBe(200);
  expect((await request("/sessions/" + sid + "/snapshot", { headers: auth })).status).toBe(403);
  expect((await request("/sessions/" + sid + "/participants", { headers: auth })).status).toBe(403);
  const ownerIdentity = await request("/sessions/" + sid + "/identity", { headers: { Cookie: cookie, Origin: origin } });
  expect(ownerIdentity.status).toBe(200);
  expect(parseSchema("IdentityResponse", await ownerIdentity.json()).data.participant.role).toBe("dispatcher");
});
