import { afterEach, expect, it } from "vitest";
import { reset, SELF } from "cloudflare:test";
import { parseSchema } from "@floodops/contracts";
afterEach(reset);
declare const __MVP_PNG__: number[];
const key = () => crypto.randomUUID();
const request = (path: string, init?: RequestInit) => SELF.fetch("https://floodops.test/api/v1" + path, init);
it("runs real composed catalog -> normalized private media -> pending report without auto knowledge/award", async () => {
  const catalog = await request("/scenarios");
  expect(catalog.status).toBe(200);
  const selected = parseSchema("ScenarioSummaryListResponse", await catalog.json()).data.items[0]!;
  const created = await request("/sessions", { method: "POST", headers: { "Content-Type": "application/json", "Idempotency-Key": key(), "X-Client-Request-Scope": key(), "CF-Connecting-IP": "192.0.2.50" }, body: JSON.stringify({ scenario_id: selected.scenario_id, scenario_version: selected.version, client_type: "native" }) });
  expect(created.status).toBe(201);
  const owner = parseSchema("SessionCreatedResponse", await created.json()).data;
  const prefix = "/sessions/" + owner.session.session_id;
  const auth = { Authorization: "Bearer " + owner.credential.access_token };
  const json = () => ({ ...auth, "Content-Type": "application/json", "Idempotency-Key": key() });
  const config = parseSchema("ScenarioConfigResponse", await (await request(prefix + "/configuration", { headers: auth })).json()).data;
  const before = parseSchema("KnowledgeResponse", await (await request(prefix + "/knowledge", { headers: auth })).json()).data;
  const bytes = new Uint8Array(__MVP_PNG__);
  const reserved = await request(prefix + "/media-uploads", { method: "POST", headers: json(), body: JSON.stringify({ content_type: "image/png", byte_length: bytes.byteLength, original_filename: "project-authored-functional.png" }) });
  expect(reserved.status).toBe(201);
  const upload = parseSchema("MediaUploadResponse", await reserved.json()).data;
  const put = await request(prefix + "/media-uploads/" + upload.upload_id + "/content", { method: "PUT", headers: { ...auth, "Content-Type": "application/octet-stream", "Idempotency-Key": key() }, body: bytes });
  expect(put.status).toBe(200);
  const completed = await request(prefix + "/media-uploads/" + upload.upload_id + "/completion", { method: "POST", headers: json(), body: JSON.stringify({ confirm_uploaded: true }) });
  expect(completed.status).toBe(201);
  const media = parseSchema("MediaResponse", await completed.json()).data;
  const derivative = await request(prefix + "/media/" + media.media_id, { headers: auth });
  expect(derivative.status).toBe(200);
  expect(derivative.headers.get("X-Content-Type-Options")).toBe("nosniff");
  const digest = await crypto.subtle.digest("SHA-256", await derivative.arrayBuffer());
  expect([...new Uint8Array(digest)].map(byte => byte.toString(16).padStart(2, "0")).join("")).toBe(media.sha256);
  const submitted = await request(prefix + "/reports", { method: "POST", headers: { ...json(), "If-Match": created.headers.get("ETag")! }, body: JSON.stringify({ kind: "citizen", reporter_entity_id: "contributor_functional1", media_id: media.media_id, fixture_photo_id: null,
    segment_id: "seg_edge27", coordinate: [106.701, 10.7705], captured_at: config.t0, captured_sim_minute: 0, vehicle_types: ["motorbike"], description: "Project-authored functional MVP image report" }) });
  expect(submitted.status).toBe(201);
  const report = parseSchema("ReportResponse", await submitted.json()).data;
  expect(report.status).toBe("pending_review");
  expect(report.award_id).toBeNull();
  expect(report.observation_ids).toEqual([]);
  const after = parseSchema("KnowledgeResponse", await (await request(prefix + "/knowledge", { headers: auth })).json()).data;
  expect(after).toEqual(before);
  const clock = parseSchema("SimulationClockResponse", await (await request(prefix + "/simulation", { headers: auth })).json()).data;
  expect(clock.now_minute).toBe(0);
});
