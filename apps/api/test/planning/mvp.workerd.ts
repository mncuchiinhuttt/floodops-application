import { afterEach, expect, it } from "vitest";
import { reset } from "cloudflare:test";
import { parseSchema } from "@floodops/contracts";
import { create, get, post, plan, run, snapshot, key, auth, request, invite } from "./runtime-fixtures";
afterEach(reset);
it("actual Hono/DO job -> approval -> dry-run -> atomic Execute -> production-policy advance", async () => {
  const f = await create(), before = await run(f), proposal = await plan(f), afterProposal = await snapshot(f);
  expect(proposal.status).toBe("pending_approval"); expect(afterProposal.meta.revision).toBe(0);
  expect((await run(f)).branches).toEqual(before.branches);
  const driver = await invite(f, "driver");
  expect((await get(driver, "/routes/" + proposal.route_ids[0])).status).toBe(404);
  const decision = await post(f, "/plans/" + proposal.plan_id + "/decisions",
    { action_ids: proposal.actions.map(a => a.action_id), decision: "approve", reason: "Explicit dispatcher test approval" });
  expect(decision.status).toBe(200); parseSchema("DecisionResultResponse", await decision.json());
  expect((await snapshot(f)).meta.revision).toBe(0); expect((await run(f)).branches).toEqual(before.branches);
  const groups = proposal.groups.map(g => g.group_id);
  const dry = await post(f, "/plans/" + proposal.plan_id + "/dry-runs", { group_ids: groups });
  expect(dry.status).toBe(200); expect(parseSchema("DryRunResultResponse", await dry.json()).data?.feasible).toBe(true);
  expect((await snapshot(f)).meta.revision).toBe(0);
  const id = key(), execute = () => post(f, "/plans/" + proposal.plan_id + "/executions", { group_ids: groups }, id);
  const committed = await execute(); expect(committed.status).toBe(201);
  const outcome = parseSchema("ExecutionResponse", await committed.json()).data!;
  expect(outcome.before_revision).toBe(0); expect(outcome.after_revision).toBe(1);
  expect(parseSchema("ExecutionResponse", await (await execute()).json()).data).toEqual(outcome);
  expect((await snapshot(f)).meta.revision).toBe(1);
  const operations = parseSchema("OperationsResponse", await (await get(f, "/operations")).json()).data!;
  const routeId = operations.branches.find(b => b.branch_id === "floodops")!.active_route_ids[0]!;
  expect((await get(driver, "/routes/" + routeId)).status).toBe(200);
  const notifications = await get(f, "/notifications"); expect(notifications.status).toBe(200);
  expect(parseSchema("NotificationListResponse", await notifications.json()).data!.items.length).toBeGreaterThan(0);
  const etag = '"s:' + f.id + ':g:0:r:1"';
  const advance = await post(f, "/simulation/advances", { target_sim_minute: 2.9 }, key(), etag);
  expect(advance.status).toBe(202);
  for (let i = 0; i < 60 && (await snapshot(f)).meta.status === "advancing"; i++) await get(f, "/simulation");
  const moved = await run(f);
  expect(moved.branches.floodops!.operations.orders.find(o => o.order_id === "ord_order1")!.delivered_at_minute).toBe(2.75);
  expect(moved.log.some(e => e.branch === "floodops" && e.kind === "entry" && e.segmentId === "seg_edge27")).toBe(true);
  expect(moved.log.some(e => e.branch === "static" && e.kind === "entry" && e.segmentId === "seg_edge27")).toBe(false);
});
it("missing provider, missing CAS, forbidden actor and unapproved Execute fail without operations mutation", async () => {
  const missing = await create(true), missingBefore = await snapshot(missing);
  const unavailable = await post(missing, "/planning-jobs", { cause: "manual", cause_entity_ids: [] });
  expect(unavailable.status).toBe(503); expect(parseSchema("ErrorResponse", await unavailable.json()).error?.code).toBe("MODEL_UNAVAILABLE");
  expect((await snapshot(missing)).values).toEqual(missingBefore.values);
  const f = await create(), before = await run(f);
  expect((await post(f, "/planning-jobs", { cause: "manual", cause_entity_ids: [] }, key(), null)).status).toBe(428);
  const member = await invite(f, "contributor");
  expect((await post(member, "/planning-jobs", { cause: "manual", cause_entity_ids: [] })).status).toBe(403);
  const proposal = await plan(f);
  expect((await post(f, "/plans/" + proposal.plan_id + "/executions", { group_ids: proposal.groups.map(g => g.group_id) })).status).toBe(422);
  expect((await run(f)).branches).toEqual(before.branches); expect((await snapshot(f)).meta.revision).toBe(0);
  const raw = await get(f, "/planning-jobs/" + proposal.planning_job_id), text = await raw.text();
  expect(text.includes("nonce")).toBe(false); expect(text.includes("capturedValues")).toBe(false); expect(text.includes(f.token)).toBe(false);
  expect((await request("/sessions/" + f.id + "/plans")).status).toBe(401);
});
it("same-revision new job supersedes the old proposal; stale Execute cannot use approvals", async () => {
  const f = await create(), first = await plan(f);
  await post(f, "/plans/" + first.plan_id + "/decisions", { action_ids: first.actions.map(a => a.action_id), decision: "approve", reason: "First proposal" });
  const second = await plan(f); expect(second.plan_id).not.toBe(first.plan_id);
  const response = await post(f, "/plans/" + first.plan_id + "/executions", { group_ids: first.groups.map(g => g.group_id) });
  expect(response.status).toBe(409); expect((await snapshot(f)).meta.revision).toBe(0);
  expect(parseSchema("PlanResponse", await (await get(f, "/plans/" + first.plan_id)).json()).data?.status).toBe("needs_replan");
});
it("old Execute replay remains stable after latest-pointer change and Reset rejects old credentials", async () => {
  const f = await create(), p = await plan(f);
  await post(f, "/plans/" + p.plan_id + "/decisions", { action_ids: p.actions.map(a => a.action_id), decision: "approve", reason: "Approve" });
  const id = key(), body = { group_ids: p.groups.map(g => g.group_id) };
  const first = parseSchema("ExecutionResponse", await (await post(f, "/plans/" + p.plan_id + "/executions", body, id)).json()).data!;
  f.etag = '"s:' + f.id + ':g:0:r:1"'; await plan(f);
  const replay = await post(f, "/plans/" + p.plan_id + "/executions", body, id, '"s:' + f.id + ':g:0:r:0"');
  expect(replay.status).toBe(201); expect(parseSchema("ExecutionResponse", await replay.json()).data).toEqual(first);
  const resetResponse = await post(f, "/resets", { client_type: "native", confirm: true });
  expect(resetResponse.status).toBe(201);
  expect((await get(f, "/operations")).status).toBe(410);
  expect((await request("/sessions/" + f.id + "/operations", { headers: auth(f) })).status).toBe(410);
});
